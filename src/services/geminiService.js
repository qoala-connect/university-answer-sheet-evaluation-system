export const DEFAULT_GEMINI_API_KEY = import.meta.env.VITE_GEMINI_API_KEY || "";
export const DEFAULT_GEMINI_MODEL = "gemini-3.6-flash";

/**
 * Convert any browser File (image or other) to Base64 data and mime type
 */
export async function fileToBase64(file) {
  return new Promise((resolve, reject) => {
    const reader = new FileReader();
    reader.onload = () => {
      const dataUrl = reader.result;
      const base64Data = dataUrl.split(',')[1];
      resolve({
        dataUrl,
        base64: base64Data,
        mimeType: file.type || 'image/jpeg'
      });
    };
    reader.onerror = error => reject(error);
    reader.readAsDataURL(file);
  });
}

/**
 * Render all pages of an uploaded PDF file into an array of JPEG Data URLs using pdfjs-dist
 */
export async function renderPdfToImages(file) {
  try {
    const pdfjsLib = await import('pdfjs-dist');
    // Set worker
    if (!pdfjsLib.GlobalWorkerOptions.workerSrc) {
      pdfjsLib.GlobalWorkerOptions.workerSrc = `https://cdnjs.cloudflare.com/ajax/libs/pdf.js/${pdfjsLib.version || '4.10.38'}/pdf.worker.min.mjs`;
    }

    const arrayBuffer = await file.arrayBuffer();
    const loadingTask = pdfjsLib.getDocument({ data: arrayBuffer });
    const pdf = await loadingTask.promise;
    const pageImages = [];

    for (let pageNum = 1; pageNum <= pdf.numPages; pageNum++) {
      const page = await pdf.getPage(pageNum);
      const viewport = page.getViewport({ scale: 1.8 });
      const canvas = document.createElement('canvas');
      const context = canvas.getContext('2d');
      canvas.height = viewport.height;
      canvas.width = viewport.width;

      await page.render({ canvasContext: context, viewport }).promise;
      const dataUrl = canvas.toDataURL('image/jpeg', 0.90);
      pageImages.push(dataUrl);
    }

    return pageImages;
  } catch (err) {
    console.warn("PDF.js in-browser rendering fallback:", err);
    // If PDF.js fails or worker is blocked, return empty array and send raw PDF to Gemini directly
    return [];
  }
}

/**
 * Call Gemini 3.6 Multimodal Engine via REST API
 */
async function callGeminiApi({ parts, apiKey = DEFAULT_GEMINI_API_KEY, model = DEFAULT_GEMINI_MODEL, responseMimeType = "application/json" }) {
  const effectiveKey = apiKey || DEFAULT_GEMINI_API_KEY;
  const url = `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${effectiveKey}`;

  const payload = {
    contents: [{ parts }],
    generationConfig: {
      temperature: 0.2,
      response_mime_type: responseMimeType
    }
  };

  const response = await fetch(url, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(payload)
  });

  if (!response.ok) {
    const errText = await response.text();
    throw new Error(`Gemini 3.6 Multimodal Engine API Error (${response.status}): ${errText}`);
  }

  const json = await response.json();
  const text = json?.candidates?.[0]?.content?.parts?.[0]?.text;
  if (!text) {
    throw new Error("No response generated by Gemini 3.6 Multimodal Engine.");
  }

  return responseMimeType === "application/json" ? JSON.parse(text) : text;
}

/**
 * 1. Analyze Question Paper with Gemini 3.6 Multimodal Engine: Auto-detects Subject, Evaluation Mode ('Assignment' | 'Quiz' | 'Examination'), and Questions
 */
export async function analyzeQuestionPaperWithGemini({ file, apiKey = DEFAULT_GEMINI_API_KEY, model = DEFAULT_GEMINI_MODEL }) {
  const parts = [];

  const prompt = `You are a Senior University Controller of Examinations and Accreditation Auditor powered by the Gemini 3.6 Multimodal Vision Engine.
Analyze this university Question Paper document in detail:

1. SUBJECT / COURSE:
   - Identify the full Subject Name (e.g. "Linear Algebra and Matrix Theory", "Advanced Theory of Turbomachinery", "Operating Systems & System Architecture", "Digital Signal Processing", etc.).
   - Generate or detect an academic Subject Code (e.g. "MATH-202", "ME-617", "CS-301", "ECE-304").
   - Identify appropriate academic Department (e.g. "Mathematics & Computing", "Mechanical & Aerospace Engineering", "Computer Science & Engineering", etc.).

2. EVALUATION MODE (CRITICAL):
   - You MUST auto-detect and categorize this document into strictly ONE of the three modes:
     * "Assignment" (if document says "Assignment", "Homework", "Problem Set", "Take-Home Assignment", etc.)
     * "Quiz" (if document says "Quiz", "Class Test", "Surprise Test", "Unit Quiz", etc.)
     * "Examination" (if document says "Examination", "End-Semester", "Mid-Semester", "Final Examination", "Term Exam", etc.)

3. EVALUATION TITLE & METADATA:
   - Specific Title (e.g. "Question Paper: Assignment - 2", "Quiz - 2 (ME 617A): Turbomachinery", "Online Exam-II (Paper Code-D) (ME-617): Advanced Theory of Turbomachinery")
   - Calculate Total Maximum Marks (sum of question marks, typically 75, 100, 50, or 25).
   - Semester & Academic Session.

4. QUESTIONS BREAKDOWN:
   - List each question or sub-question (e.g. "Q1(a)", "Q1(b)", "Q2", etc.)
   - Question text / prompt
   - Maximum marks allocated
   - Course Outcome tag ("CO1", "CO2", "CO3", "CO4")
   - Bloom's Taxonomy Level (e.g. "L2 - Understand", "L3 - Apply", "L4 - Analyze", "L5 - Evaluate")
   - Model answer summary or key derivation expectations

Return pure JSON conforming to this schema:
{
  "subject": string,
  "subjectCode": string,
  "department": string,
  "evaluationMode": "Assignment" | "Quiz" | "Examination",
  "title": string,
  "totalMarks": number,
  "semester": string,
  "questions": [
    {
      "qNo": string,
      "title": string,
      "questionText": string,
      "maxMarks": number,
      "co": string,
      "bloom": string,
      "modelAnswer": string,
      "rubricBreakdown": [
        { "criteria": string, "points": number }
      ]
    }
  ]
}`;

  parts.push({ text: prompt });

  // Add the file part
  const { base64, mimeType } = await fileToBase64(file);
  parts.push({
    inline_data: {
      mime_type: mimeType,
      data: base64
    }
  });

  return await callGeminiApi({ parts, apiKey, model });
}

/**
 * 2. Evaluate Student Answer Sheet against Question Paper using Gemini 3.6 Multimodal Engine
 */
export async function evaluateStudentScriptWithGemini({
  scriptFile,
  scriptPages = [],
  qpInfo,
  candidateName = '',
  candidateUsn = '',
  apiKey = DEFAULT_GEMINI_API_KEY,
  model = DEFAULT_GEMINI_MODEL
}) {
  const parts = [];

  const prompt = `You are a University Chief Examiner and Senior Accreditation Auditor powered by the Gemini 3.6 Multimodal Vision Engine. You are evaluating a handwritten student answer sheet.
Question Paper Details:
- Subject: ${qpInfo.subject} (${qpInfo.subjectCode})
- Evaluation Mode: ${qpInfo.evaluationMode}
- Total Marks: ${qpInfo.totalMarks}
- Rubric Blueprint:
${JSON.stringify(qpInfo.questions, null, 2)}

INSTRUCTIONS:
1. CANDIDATE IDENTIFICATION:
   - Look at the student handwritten header. Detect the candidate's actual written Name and Roll No / USN.
   - If written on paper, use the detected values. Otherwise fall back to provided: Name="${candidateName}", USN="${candidateUsn}".

2. STEP-BY-STEP MATHEMATICAL & TECHNICAL EVALUATION:
   - For every question in the Question Paper, inspect the student's handwritten work.
   - Transcribe the student's exact derivation and mathematical notation into LaTeX/text under "studentInput".
   - Award step marks based on mathematical rigor, valid alternative solutions (e.g. alternate basis choices in linear algebra), and final answers.
   - For any deductions, provide specific constructive notes in "mistakesInline" with the exact penalty.
   - Write clear, academic "aiFeedback" for each question.
   - Identify the starting page number (1-indexed) where each answer was found.

3. OVERALL EVALUATION LEDGER:
   - Calculate totalMarks awarded out of ${qpInfo.totalMarks}.
   - Calculate percentage = (totalMarks / ${qpInfo.totalMarks}) * 100.
   - Assign letter grade:
     * >= 95%: "S+ (Outstanding)"
     * >= 85%: "S (Excellent)"
     * >= 75%: "A (Very Good)"
     * >= 65%: "B (Good)"
     * >= 50%: "C (Average)"
     * < 50%: "F (Remedial)"
   - Compute Course Outcome (CO) attainment percentages: { "CO1": number, "CO2": number, "CO3": number, "CO4": number }
   - Identify strongestAreas (array of strings) and weakestAreas (array of strings).

Return pure JSON conforming to this schema:
{
  "detectedName": string,
  "detectedUsn": string,
  "totalMarks": number,
  "maxMarks": number,
  "percentage": number,
  "grade": string,
  "gradePoint": number,
  "coAttainment": {
    "CO1": number,
    "CO2": number,
    "CO3": number,
    "CO4": number
  },
  "strongestAreas": string[],
  "weakestAreas": string[],
  "answers": [
    {
      "qNo": string,
      "title": string,
      "co": string,
      "maxMarks": number,
      "awardedMarks": number,
      "startPage": number,
      "pages": number[],
      "studentInput": string,
      "aiFeedback": string,
      "mistakesInline": [
        { "text": string, "type": "warning" | "error", "note": string, "penalty": number }
      ]
    }
  ]
}`;

  parts.push({ text: prompt });

  // Attach images or raw PDF of the student booklet
  if (scriptPages && scriptPages.length > 0) {
    // Send up to first 6-8 pages to stay within token context comfortably
    const pagesToSend = scriptPages.slice(0, 8);
    for (const pageDataUrl of pagesToSend) {
      const base64 = pageDataUrl.includes(',') ? pageDataUrl.split(',')[1] : pageDataUrl;
      parts.push({
        inline_data: {
          mime_type: 'image/jpeg',
          data: base64
        }
      });
    }
  } else if (scriptFile) {
    const { base64, mimeType } = await fileToBase64(scriptFile);
    parts.push({
      inline_data: {
        mime_type: mimeType,
        data: base64
      }
    });
  }

  return await callGeminiApi({ parts, apiKey, model });
}
